"""ClamAV database management.

Handles:
- Running freshclam to update the virus database (platform-aware)
- Checking database status
- Generating freshclam.conf (Windows only)

Platform differences:
  Linux:   runs `pkexec freshclam` (or `sudo` fallback) — writes to system /var/lib/clamav
  Windows: generates freshclam.conf pointing to %APPDATA%\\... then runs freshclam
"""

import os
import subprocess
import threading

from backends import backend
from core.constants import CLAMAV_DB_MIRROR
from core.database_update import DatabaseUpdateResult

# Manual and automatic updates never run freshclam at the same time.
DATABASE_UPDATE_LOCK = threading.Lock()
# Automatic refresh of LibreWard's own database while the app runs.
AUTO_UPDATE_INTERVAL = 12 * 3600
AUTO_UPDATE_RETRY = 2 * 3600


def auto_update_due(now, last_attempt, last_succeeded=True):
    """Whether an automatic update is due; restarts never shorten the interval."""
    if not isinstance(last_attempt, (int, float)) or last_attempt > now:
        return True
    return now - last_attempt >= (AUTO_UPDATE_INTERVAL if last_succeeded else AUTO_UPDATE_RETRY)


def own_database_needs_refresh():
    """Automatic updates refresh only LibreWard's own existing database.

    A current system database is the distribution's job, and the first large
    download stays a choice the user makes in setup.
    """
    from backends.base import newest_database_time
    own = backend.db_dir() if backend.manages_own_database() else None
    return (own is not None and not backend.system_database_current()
            and newest_database_time(own) is not None)


# ── freshclam.conf generation ───────────────────────────────────────

def generate_freshclam_conf(freshclam_path: str) -> str | None:
    """Generate (or overwrite) freshclam.conf in the app data directory.

    Used for LibreWard's own database (Windows, and Linux without a current
    system database). Returns None when the platform has no own database.
    """
    if not backend.manages_own_database():
        return None

    db_dir = backend.db_dir()
    if db_dir is None:
        return None

    db_dir.mkdir(parents=True, exist_ok=True)
    backend.log_dir().mkdir(parents=True, exist_ok=True)

    db_dir_str = str(db_dir.resolve())
    log_file = str((backend.log_dir() / "freshclam.log").resolve())
    conf_path = backend.data_dir() / "freshclam.conf"

    content = [
        "# Generated by LibreWard",
        "# Updates go to the app-data directory, never inside the runtime folder.",
        f"DatabaseDirectory {db_dir_str}",
        f"UpdateLogFile {log_file}",
        f"DatabaseMirror {CLAMAV_DB_MIRROR}",
        "",
        "# Safety limits",
        "MaxAttempts 3",
        "ConnectTimeout 30",
        "ReceiveTimeout 60",
        "",
        "# Non-interactive mode",
        "Foreground yes",
        "",
        "# Number of database checks per day (0 = skip time check, update every run)",
        "Checks 1",
        "",
        "# Logging",
        "LogVerbose no",
    ]

    conf_path.write_text("\n".join(content), encoding="utf-8")
    return str(conf_path)


# ── run freshclam ───────────────────────────────────────────────────

def _run_freshclam_cmd(cmd: list[str], log_callback=None) -> tuple[bool, str]:
    """Execute a command and capture output. Returns (success, output_text)."""
    if log_callback:
        tool = os.path.basename(cmd[0]) if cmd else "freshclam"
        log_callback(f"Running: {tool}\n")

    try:
        proc = backend.start_process(
            cmd,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            encoding="utf-8",
            errors="replace",
            bufsize=1,
        )

        output_lines: list[str] = []
        if proc.stdout:
            for line in proc.stdout:
                output_lines.append(line)
                if log_callback:
                    log_callback(line)

        return_code = proc.wait()
        success = return_code == 0
        return success, "".join(output_lines)

    except FileNotFoundError:
        msg = f"ERROR: {cmd[0]} not found.\n"
        if log_callback:
            log_callback(msg)
        return False, msg

    except Exception as e:
        msg = f"ERROR: Failed to run freshclam: {e}\n"
        if log_callback:
            log_callback(msg)
        return False, msg


def run_freshclam_update(
    freshclam_path: str,
    conf_path: str | None = None,
    log_callback=None,
    wait: bool = True,
) -> tuple[bool, str] | DatabaseUpdateResult:
    """Serialized wrapper; with wait=False a running update makes this a pending no-op."""
    if not DATABASE_UPDATE_LOCK.acquire(blocking=wait):
        return DatabaseUpdateResult(False, 'A virus database update is already running.\n', pending=True)
    try:
        return _run_freshclam_update(freshclam_path, conf_path, log_callback)
    finally:
        DATABASE_UPDATE_LOCK.release()


def _run_freshclam_update(
    freshclam_path: str,
    conf_path: str | None = None,
    log_callback=None,
) -> tuple[bool, str] | DatabaseUpdateResult:
    """Update the virus database LibreWard scans with.

    A current system database (Linux) needs no download. Otherwise freshclam runs
    as the user with LibreWard's own config and database directory: no password,
    and the distribution's freshclam.conf (permissions, `Example` line) does not
    matter. While the system updater is still fetching a first database, LibreWard
    waits for it instead of downloading a duplicate.
    Returns (success, output), or a pending result when the system updater owns the work.
    """
    from core.runtime import database_files
    if backend.system_database_current():
        message = 'The system virus database is up to date and kept current by your system. No download is needed.\n'
        if log_callback:
            log_callback(message)
        return True, message
    activity = backend.freshclam_activity()
    if activity and not database_files():
        message = (
            f'The system updater is downloading the virus database ({activity}).\n'
            'LibreWard waits for it instead of downloading a second copy, and checks '
            'when the database becomes available.\n'
        )
        if log_callback:
            log_callback(message)
        return DatabaseUpdateResult(False, message, pending=True)
    if conf_path is None:
        conf_path = generate_freshclam_conf(freshclam_path)
    if conf_path is None:
        return False, "ERROR: Could not generate database config.\n"
    ok, out = _run_freshclam_cmd([freshclam_path, "--config-file", conf_path], log_callback)
    if not ok and ('failed to lock the log file' in out.lower() or
                   'database is locked by another process' in out.lower()):
        message = ('Another LibreWard update is already running. Wait for it to finish, then check again.\n')
        if log_callback:
            log_callback(message)
        return DatabaseUpdateResult(False, message, pending=True)
    return ok, out


# ── database summary ────────────────────────────────────────────────

def database_summary() -> str:
    """Return a human-readable summary of the database status."""
    from core.runtime import database_files

    files = database_files()

    if not files:
        locations = backend.system_db_locations()
        dirs_str = ", ".join(str(d) for d in locations) if locations else "unknown"
        return f"Database locations: {dirs_str}\nNo database files found."

    # Find which location the files came from
    db_dir = None
    for loc in backend.system_db_locations():
        if loc.is_dir():
            db_dir = loc
            break

    dir_label = str(db_dir) if db_dir else "unknown"
    lines = [f"Database directory: {dir_label}", f"Files ({len(files)}):"]
    for f in sorted(files):
        if db_dir:
            fpath = db_dir / f
            try:
                size = fpath.stat().st_size
                if size > 1_000_000:
                    size_str = f"{size / 1_000_000:.1f} MB"
                elif size > 1_000:
                    size_str = f"{size / 1_000:.1f} KB"
                else:
                    size_str = f"{size} B"
                lines.append(f"  {f}  ({size_str})")
            except OSError:
                lines.append(f"  {f}")
        else:
            lines.append(f"  {f}")

    return "\n".join(lines)
